"""Seed map (DESIGN Amendment 15.19). Child i = SeedSequence(20261030, spawn_key=(i,)). Lists every evaluation
range with the commit at which its cell first appeared in scripts/suite/cells.json (from git history), plus the
calibration, exploratory and development ranges, and every smoke run made on evaluation seeds. Writes
scripts/suite/seed_map.md. Usage: python scripts/suite/build_seed_map.py"""
import glob
import json
import os
import subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))


def git(*a):
    return subprocess.run(["git", "-C", ROOT, *a], capture_output=True, text=True).stdout


def main():
    commits = git("log", "--format=%h %cI", "--reverse", "--", "scripts/suite/cells.json").split("\n")
    first = {}
    for line in filter(None, commits):
        h, d = line.split(" ", 1)
        tab = json.loads(git("show", f"{h}:scripts/suite/cells.json"))
        for c in tab["cells"]:
            first.setdefault(c["cell"], (h, d))
    cur = json.load(open(os.path.join(ROOT, "scripts", "suite", "cells.json")))
    L = ["# Seed map (DESIGN Amendment 15.19)", "",
         "Child index i means `numpy.random.SeedSequence(20261030, spawn_key=(i,))` (`analysis/synth.py` `child_rng`; "
         "equal to `SeedSequence(20261030).spawn(N)[i]`). Generated by `scripts/suite/build_seed_map.py` from git history.", "",
         "## Evaluation ranges (one per cell; cell c uses c·200 … c·200+199)", "",
         "| cell | kind | φ_y | child indices | first committed in | commit date | status |", "|---|---|---|---|---|---|---|"]
    for c in cur["cells"]:
        h, d = first.get(c["cell"], ("UNCOMMITTED", ""))
        st = "superseded (kept as record)" if "superseded" in c else "evaluation"
        L.append(f"| {c['cell']} | {c['kind']} | {c.get('phi', '')} | {c['child_first']:,}–{c['child_first'] + c['reps'] - 1:,} "
                 f"| {h} | {d[:19]} | {st} |")
    L += ["", "## Calibration ranges (per φ_y: 1,000 indices each; never evaluation)", "",
          "| φ_y | indices | used by |", "|---|---|---|"]
    for c in cur["calibration"]:
        a = c["child_first"]
        L.append(f"| {c['phi']} | {a:,}–{a + 999:,} | offsets 0–99 pulse calibration (`calibrate_pulse.py`, incl. bisection); "
                 f"500–599 flip calibration (`calibrate_flip.py`); 700–799 / 800–899 dynamic-range measurement "
                 f"(`measure_dynamic_range.py`); 900–949 positive-control calibration (`calibrate_posctrl.py`, "
                 f"Amendment 15.4)" + (" — extension φ_y (Amendment 15.5); no dynamic-range cells, so offsets 700–899 unused"
                                       if c["phi"] in (0.3, 0.99) else "") + " |")
    L += ["", "## Exploratory, measurement and development ranges (never evaluation)", "",
          "| indices | purpose |", "|---|---|",
          "| 10,000,000–10,000,007 | S-3 pulse probes at φ 0.9 (`probe_null3050_pulse.py`; inside the φ 0.5 calibration range) |",
          "| 10,000,000–10,000,005; 10,500,000–10,500,005 | S-3 step probe (series; step offsets) |",
          "| 20,000,000–20,004,199 | item-17 / S-2 measurement (exploratory, Amendment 10.1) |",
          "| 30,000,000 | `scripts/tests/test_compare_ref.py` fixture |",
          "| 40,000,000–40,000,024 | S-4 flip-amplitude probe (`probe_flip_amplitude.py`) |",
          "| 41,000,000–41,000,001 | development check of `synth_e2e.py` |",
          "| 42,000,000 | development check of `synth_a1layout.py` |",
          "| 43,000,000–43,000,019 | dynamic-range probe (`probe_dynamic_range.py`) |",
          "| 44,000,000–44,019,399 | Amendment 15.8 (b)(c) D_div lead-response checks (`check_ddiv_response.py`): "
          "check k = 0…9 uses 44,000,000 + k·2,000 + {0–19 population θ, 100–199 L = 75, 300–399 L = 125} |",
          "| 44,000,000–44,000,001 | development smoke run of `check_ddiv_response.py` (2026-11-08; no output kept) |",
          "| 44,000,000–44,000,002; 44,010,000–44,010,005 | θ-matchability probes on null series for the v1 → v2 fix of "
          "`check_ddiv_response.py` (2026-11-09; printed only) |",
          "| 44,000,000–44,000,002, 44,000,100–102, 44,000,300–302; 44,002,000–002, 44,002,100–102, 44,002,300–302 | "
          "smoke run of `check_ddiv_response.py` v2 at 3 replicates, φ 0.9 only (2026-11-09; output overwritten by the full run) |",
          "| 5,000,000+ | early null-timing probe (2026-10-31; killed, no output kept) |", "",
          "Pre-SeedSequence probes (`scripts/tests/probe_oracle_criterion.py`, S-1) used `default_rng([20261030, 999, r])`, "
          "a different seeding, not a child index.", "",
          "## Smoke runs on evaluation seeds (disclosure)", "",
          "Single-replicate development runs (`--out-suffix _devtest`) were made on these cells' evaluation seeds before or "
          "while the cells were committed. They checked that code ran; no decision used them. They are kept, unmerged, "
          "in the output folders.", "", "| file | replicates |", "|---|---|"]
    for f in sorted(glob.glob(os.path.join(ROOT, "scripts", "outputs", "*", "*_devtest.jsonl"))):
        reps = sorted(json.loads(l)["rep"] for l in open(f) if l.strip())
        L.append(f"| `{os.path.relpath(f, ROOT).replace(os.sep, '/')}` | {reps} |")
    open(os.path.join(ROOT, "scripts", "suite", "seed_map.md"), "w", encoding="utf-8", newline="\n").write("\n".join(L) + "\n")
    print("WROTE scripts/suite/seed_map.md;", len(cur["cells"]), "cells")


if __name__ == "__main__":
    main()
